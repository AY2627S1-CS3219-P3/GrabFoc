import { Controller, Get, Param, Query, Req, UseGuards } from '@nestjs/common';
import { AuthedRequest, denied, JwtAuthGuard } from '../common/jwt-auth.guard';
import { parseOr400, transactionsQuerySchema, userIdParamSchema } from './credit.schemas';
import { Balance, CreditsService, TransactionPage } from './credits.service';

@Controller('credits')
@UseGuards(JwtAuthGuard)
export class BalanceController {
  constructor(private readonly credits: CreditsService) {}

  @Get(':userId')
  balance(@Param('userId') rawUserId: string, @Req() req: AuthedRequest): Promise<Balance> {
    return this.credits.getBalance(this.allowedUserId(rawUserId, req, 'credit balance'));
  }

  // AI-generated by Claude Code (route decided by Jian Bing)
  @Get(':userId/transactions')
  transactions(
    @Param('userId') rawUserId: string,
    @Query() rawQuery: unknown,
    @Req() req: AuthedRequest,
  ): Promise<TransactionPage> {
    const userId = this.allowedUserId(rawUserId, req, 'credit history');
    const { limit, before } = parseOr400(transactionsQuerySchema, rawQuery, 'query');
    return this.credits.listTransactions(userId, limit, before);
  }

  /** A USER may read only their own wallet; an ADMIN may read anyone's. */
  private allowedUserId(rawUserId: string, req: AuthedRequest, what: string): string {
    const userId = parseOr400(userIdParamSchema, rawUserId, 'user id');
    if (req.caller.role !== 'ADMIN' && req.caller.id.toLowerCase() !== userId) {
      throw denied(req, 403, `You can only view your own ${what}.`, req.caller);
    }
    return userId;
  }
}
