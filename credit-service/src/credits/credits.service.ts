import type { ReleaseRequest, ReserveRequest, TransferRequest } from './credit.schemas';

export type HoldState = 'RESERVED' | 'TRANSFERRED' | 'RELEASED';

/**
 * A hold, or a marker: a RELEASED row with no requester or amount, saved when a release found no
 * hold (issue #83). A RESERVED or TRANSFERRED hold always has both (credit_holds_marker check).
 */
export interface Hold {
  orderId: string;
  requesterId: string | null;
  courierId: string | null;
  amount: number | null;
  state: HoldState;
}

/** A hold that moved credits, so it has its requester and amount. */
type LiveHold = Hold & { requesterId: string; amount: number };

export interface Balance {
  userId: string;
  available: number;
  reserved: number;
}

// AI-generated by Claude Code (route decided by Jian Bing)
export interface Transaction {
  id: number;
  orderId: string | null;
  type: TransactionType;
  availableChange: number;
  reservedChange: number;
  createdAt: string;
}

/** `nextBefore` is the `before` for the next page, or null on the last page. */
export interface TransactionPage {
  items: Transaction[];
  nextBefore: number | null;
}

/** `created` is false when the request repeated one already applied, so nothing changed. */
export interface HoldResult {
  hold: Hold;
  created: boolean;
}

interface HoldRow {
  order_id: string;
  requester_id: string | null;
  courier_id: string | null;
  amount: number | null;
  state: HoldState;
}

const HOLD_COLUMNS = 'order_id, requester_id, courier_id, amount, state';

function toHold(row: HoldRow): Hold {
  return {
    orderId: row.order_id,
    requesterId: row.requester_id,
    courierId: row.courier_id,
    amount: row.amount,
    state: row.state,
  };
}

// AI-generated by Claude Code (design decided by Jian Bing)
type TransactionType = 'GRANT' | 'RESERVE' | 'TRANSFER_OUT' | 'TRANSFER_IN' | 'RELEASE';

/**
 * Appends one row to credit_transactions. Called inside the same transaction as the balance change
 * it describes (root AGENTS.md §8), so a user's rows always add up to their balance.
 */
async function recordTransaction(
  client: PoolClient,
  userId: string,
  orderId: string | null,
  type: TransactionType,
  availableChange: number,
  reservedChange: number,
): Promise<void> {
  await client.query(
    `INSERT INTO credit_transactions (user_id, order_id, type, available_change, reserved_change)
     VALUES ($1, $2, $3, $4, $5)`,
    [userId, orderId, type, availableChange, reservedChange],
  );
}

/**
 * Creates the user's account with the starting credits if it doesn't exist yet, recording the
 * grant. Returns false when it already existed.
 */
async function ensureAccount(client: PoolClient, userId: string): Promise<boolean> {
  const { rowCount } = await client.query(
    'INSERT INTO credit_accounts (user_id) VALUES ($1) ON CONFLICT DO NOTHING',
    [userId],
  );
  if (rowCount !== 1) return false;
  await recordTransaction(client, userId, null, 'GRANT', STARTING_CREDITS, 0);
  return true;
}

async function findHold(client: PoolClient, orderId: string): Promise<Hold | undefined> {
  const { rows } = await client.query<HoldRow>(`SELECT ${HOLD_COLUMNS} FROM credit_holds WHERE order_id = $1`, [
    orderId,
  ]);
  return rows[0] && toHold(rows[0]);
}

@Injectable()
export class CreditsService {
  constructor(@Inject(PG_POOL) private readonly pool: Pool) {}

  /** Runs `work` in one transaction: every change commits together or none does (NFR1.4). */
  private async inTransaction<T>(work: (client: PoolClient) => Promise<T>): Promise<T> {
    const client = await this.pool.connect();
    try {
      await client.query('BEGIN');
      const result = await work(client);
      await client.query('COMMIT');
      return result;
    } catch (err) {
      await client.query('ROLLBACK');
      throw err;
    } finally {
      client.release();
    }
  }

  /** Moves `amount` from the requester's available to reserved credits for a new order (CSFR2). */
  reserve({ orderId, requesterId, amount }: ReserveRequest): Promise<HoldResult> {
    return this.inTransaction(async (client) => {
      await ensureAccount(client, requesterId);

      // The unique order id makes a second insert for the same order do nothing. A concurrent
      // duplicate waits here until the first transaction commits or rolls back.
      const inserted = await client.query<HoldRow>(
        `INSERT INTO credit_holds (order_id, requester_id, amount) VALUES ($1, $2, $3)
         ON CONFLICT (order_id) DO NOTHING RETURNING ${HOLD_COLUMNS}`,
        [orderId, requesterId, amount],
      );

      if (inserted.rowCount === 0) {
        const existing = (await findHold(client, orderId))!;
        // AI-generated by Claude Code (issue #83; 409 decided by Jian Bing)
        // The order was released before this reserve arrived (Order gave up waiting): hold nothing.
        if (existing.requesterId === null) {
          throw new ProblemException(
            409,
            `Order ${orderId} was released before its credits were reserved.`,
            ErrorCode.ALREADY_RELEASED,
          );
        }
        if (existing.requesterId !== requesterId || existing.amount !== amount) {
          throw new ProblemException(
            409,
            `Order ${orderId} already has credits reserved with a different requester or amount.`,
            ErrorCode.HOLD_MISMATCH,
          );
        }
        return { hold: existing, created: false };
      }

      // The check and the change are one statement, so two orders at once can't overdraw (NFR2.1.1).
      const debited = await client.query(
        `UPDATE credit_accounts
            SET available = available - $2, reserved = reserved + $2, updated_at = now()
          WHERE user_id = $1 AND available >= $2`,
        [requesterId, amount],
      );
      if (debited.rowCount === 0) {
        // Throwing rolls back the hold inserted above.
        throw new ProblemException(409, 'Insufficient credits to reserve this amount.', ErrorCode.INSUFFICIENT_CREDITS);
      }
      await recordTransaction(client, requesterId, orderId, 'RESERVE', -amount, amount);

      return { hold: toHold(inserted.rows[0]), created: true };
    });
  }

  /** Pays a completed order's reserved credits to its courier (CSFR3). */
  transfer({ orderId, courierId }: TransferRequest): Promise<HoldResult> {
    return this.inTransaction(async (client) => {
      await ensureAccount(client, courierId);

      // Only a RESERVED hold moves on. A concurrent transfer or release waits for this row's lock,
      // then finds the state changed and updates nothing.
      const moved = await client.query<HoldRow>(
        `UPDATE credit_holds SET state = 'TRANSFERRED', courier_id = $2, updated_at = now()
          WHERE order_id = $1 AND state = 'RESERVED' AND requester_id <> $2
          RETURNING ${HOLD_COLUMNS}`,
        [orderId, courierId],
      );

      if (moved.rowCount === 0) {
        const existing = await findHold(client, orderId);
        if (!existing) {
          throw new ProblemException(404, `No credits are reserved for order ${orderId}.`, ErrorCode.HOLD_NOT_FOUND);
        }
        if (existing.state === 'TRANSFERRED' && existing.courierId === courierId) {
          return { hold: existing, created: false };
        }
        if (existing.state === 'RESERVED') {
          throw new ProblemException(409, 'The courier cannot be the order’s requester.', ErrorCode.COURIER_IS_REQUESTER);
        }
        if (existing.state === 'RELEASED') {
          throw new ProblemException(
            409,
            `Order ${orderId}'s credits were already released to the requester.`,
            ErrorCode.ALREADY_RELEASED,
          );
        }
        throw new ProblemException(
          409,
          `Order ${orderId}'s credits were already transferred to a different courier.`,
          ErrorCode.ALREADY_TRANSFERRED,
        );
      }

      const hold = toHold(moved.rows[0]) as LiveHold; // it was RESERVED
      // Change the two accounts in a fixed order (by user id), so two transfers between the same
      // pair of users in opposite directions can't deadlock.
      const changes = [
        {
          userId: hold.requesterId,
          sql: 'UPDATE credit_accounts SET reserved = reserved - $2, updated_at = now() WHERE user_id = $1',
        },
        {
          userId: hold.courierId!,
          sql: 'UPDATE credit_accounts SET available = available + $2, updated_at = now() WHERE user_id = $1',
        },
      ].sort((a, b) => (a.userId < b.userId ? -1 : 1));
      for (const change of changes) {
        await client.query(change.sql, [change.userId, hold.amount]);
      }
      await recordTransaction(client, hold.requesterId, orderId, 'TRANSFER_OUT', 0, -hold.amount);
      await recordTransaction(client, hold.courierId!, orderId, 'TRANSFER_IN', hold.amount, 0);

      return { hold, created: true };
    });
  }

  /** Returns a cancelled order's reserved credits to the requester's available balance (CSFR4). */
  release({ orderId }: ReleaseRequest): Promise<HoldResult> {
    return this.inTransaction(async (client) => {
      // AI-generated by Claude Code (issue #83; marker design decided by Jian Bing)
      // With no hold for the order, leave a marker so a slow reserve still running for it holds
      // nothing. Insert first: if that reserve has saved its hold but not committed, this waits for
      // it, then finds the hold and releases it below. Either way no live hold is left behind.
      const marker = await client.query<HoldRow>(
        `INSERT INTO credit_holds (order_id, state) VALUES ($1, 'RELEASED')
         ON CONFLICT (order_id) DO NOTHING RETURNING ${HOLD_COLUMNS}`,
        [orderId],
      );
      if (marker.rowCount === 1) return { hold: toHold(marker.rows[0]), created: true };

      const moved = await client.query<HoldRow>(
        `UPDATE credit_holds SET state = 'RELEASED', updated_at = now()
          WHERE order_id = $1 AND state = 'RESERVED'
          RETURNING ${HOLD_COLUMNS}`,
        [orderId],
      );

      if (moved.rowCount === 0) {
        const existing = (await findHold(client, orderId))!; // the insert above found it
        if (existing.state === 'RELEASED') return { hold: existing, created: false };
        throw new ProblemException(
          409,
          `Order ${orderId}'s credits were already transferred to its courier.`,
          ErrorCode.ALREADY_TRANSFERRED,
        );
      }

      const hold = toHold(moved.rows[0]) as LiveHold; // it was RESERVED
      await client.query(
        `UPDATE credit_accounts
            SET available = available + $2, reserved = reserved - $2, updated_at = now()
          WHERE user_id = $1`,
        [hold.requesterId, hold.amount],
      );
      await recordTransaction(client, hold.requesterId, orderId, 'RELEASE', hold.amount, -hold.amount);
      return { hold, created: true };
    });
  }

  /** A user's balance; 404 WALLET_NOT_FOUND when their wallet doesn't exist yet. Never creates one. */
  // AI-generated by Claude Code (route decided by Jian Bing)
  /** The user's history, newest first, starting after the row `before` when given. */
  async listTransactions(userId: string, limit: number, before?: number): Promise<TransactionPage> {
    await this.getBalance(userId); // 404 WALLET_NOT_FOUND, as the balance route answers
    // One row more than asked for tells whether another page exists.
    const { rows } = await this.pool.query<{
      id: string;
      order_id: string | null;
      type: TransactionType;
      available_change: number;
      reserved_change: number;
      created_at: Date;
    }>(
      `SELECT id, order_id, type, available_change, reserved_change, created_at
         FROM credit_transactions
        WHERE user_id = $1 AND ($2::bigint IS NULL OR id < $2)
        ORDER BY id DESC
        LIMIT $3`,
      [userId, before ?? null, limit + 1],
    );
    const items = rows.slice(0, limit).map((r) => ({
      id: Number(r.id),
      orderId: r.order_id,
      type: r.type,
      availableChange: r.available_change,
      reservedChange: r.reserved_change,
      createdAt: r.created_at.toISOString(),
    }));
    return { items, nextBefore: rows.length > limit ? items[items.length - 1].id : null };
  }

  async getBalance(userId: string): Promise<Balance> {
    const { rows } = await this.pool.query<{ user_id: string; available: number; reserved: number }>(
      'SELECT user_id, available, reserved FROM credit_accounts WHERE user_id = $1',
      [userId],
    );
    if (!rows[0]) {
      throw new ProblemException(404, 'This user has no credit wallet yet.', ErrorCode.WALLET_NOT_FOUND);
    }
    return { userId: rows[0].user_id, available: rows[0].available, reserved: rows[0].reserved };
  }

  /** Creates a wallet with the starting credits; false when it already existed (spec §4.1). */
  async createWallet(userId: string): Promise<boolean> {
    return this.inTransaction((client) => ensureAccount(client, userId));
  }
}
