import { Pool, PoolClient } from 'pg';
import { openTestDatabase } from '../test/database';
import { SCHEMA_SQL } from './schema';

let pool: Pool;
let client: PoolClient;
const schema = `migration_${process.pid}`;

beforeAll(async () => {
  pool = await openTestDatabase();
  client = await pool.connect();
  // A schema of its own, so the other test files' tables are untouched.
  await client.query(`CREATE SCHEMA ${schema}`);
  await client.query(`SET search_path TO ${schema}`);
});
afterAll(async () => {
  await client.query(`DROP SCHEMA ${schema} CASCADE`);
  client.release();
  await pool.end();
});

async function columns(): Promise<Record<string, string>> {
  const { rows } = await client.query<{ column_name: string; data_type: string }>(
    `SELECT column_name, data_type FROM information_schema.columns
      WHERE table_schema = $1 AND table_name = 'credit_dead_letters'`,
    [schema],
  );
  return Object.fromEntries(rows.map((r) => [r.column_name, r.data_type]));
}

// AI-generated by Claude Code (rename decided by Jian Bing)
it('renames order_id and command_type in a table created before the generic envelope, keeping its rows but not guessing their keys', async () => {
  await client.query(`CREATE TABLE credit_dead_letters (
    id BIGSERIAL PRIMARY KEY, event_id UUID, order_id UUID, source_topic TEXT NOT NULL,
    source_partition INTEGER, source_offset BIGINT, command_type TEXT, payload BYTEA NOT NULL,
    error TEXT NOT NULL, error_code TEXT, attempts INTEGER NOT NULL CHECK (attempts > 0),
    dead_lettered_at TIMESTAMPTZ NOT NULL, replay_claimed_at TIMESTAMPTZ, replayed_at TIMESTAMPTZ,
    UNIQUE (source_topic, event_id))`);
  await client.query(
    `INSERT INTO credit_dead_letters (order_id, source_topic, command_type, payload, error, attempts, dead_lettered_at)
     VALUES ('11111111-1111-4111-8111-111111111111', 'credit.commands', 'ReleaseCredits', 'x', 'e', 1, now())`,
  );

  await client.query(SCHEMA_SQL);
  await client.query(SCHEMA_SQL); // and again: a second start changes nothing

  const cols = await columns();
  expect(cols).toMatchObject({ message_key: 'text', message_type: 'text' });
  expect(cols).not.toHaveProperty('order_id');
  expect(cols).not.toHaveProperty('command_type');
  const { rows } = await client.query('SELECT message_key, message_type FROM credit_dead_letters');
  // The old column held the payload's orderId, not the Kafka key, so the key is unknown.
  expect(rows).toEqual([{ message_key: null, message_type: 'ReleaseCredits' }]);
});

// AI-generated by Claude Code (issue #83; marker design decided by Jian Bing)
it('lets a credit_holds table created before markers hold one, and only a RELEASED one', async () => {
  const holds = `holds_${process.pid}`;
  await client.query(`CREATE SCHEMA ${holds}`);
  await client.query(`SET search_path TO ${holds}`);
  try {
    await client.query(`CREATE TABLE credit_accounts (user_id UUID PRIMARY KEY,
      available INTEGER NOT NULL DEFAULT 10, reserved INTEGER NOT NULL DEFAULT 0,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now())`);
    await client.query(`CREATE TABLE credit_holds (order_id UUID PRIMARY KEY,
      requester_id UUID NOT NULL REFERENCES credit_accounts(user_id),
      courier_id UUID REFERENCES credit_accounts(user_id), amount INTEGER NOT NULL CHECK (amount > 0),
      state TEXT NOT NULL DEFAULT 'RESERVED' CHECK (state IN ('RESERVED', 'TRANSFERRED', 'RELEASED')),
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      CHECK ((state = 'TRANSFERRED') = (courier_id IS NOT NULL)))`);
    await client.query(`INSERT INTO credit_accounts (user_id) VALUES ('22222222-2222-4222-8222-222222222222')`);
    await client.query(`INSERT INTO credit_holds (order_id, requester_id, amount)
      VALUES ('33333333-3333-4333-8333-333333333333', '22222222-2222-4222-8222-222222222222', 3)`);

    await client.query(SCHEMA_SQL);
    await client.query(SCHEMA_SQL); // and again: a second start changes nothing

    await client.query(`INSERT INTO credit_holds (order_id, state) VALUES ('44444444-4444-4444-8444-444444444444', 'RELEASED')`);
    // A marker is only ever RELEASED, and a hold has both its requester and its amount.
    await expect(
      client.query(`INSERT INTO credit_holds (order_id) VALUES ('55555555-5555-4555-8555-555555555555')`),
    ).rejects.toThrow(/check constraint/);
    await expect(
      client.query(`INSERT INTO credit_holds (order_id, amount, state) VALUES ('66666666-6666-4666-8666-666666666666', 3, 'RELEASED')`),
    ).rejects.toThrow(/check constraint/);
    const { rows } = await client.query('SELECT order_id, amount FROM credit_holds ORDER BY order_id');
    expect(rows).toEqual([
      { order_id: '33333333-3333-4333-8333-333333333333', amount: 3 },
      { order_id: '44444444-4444-4444-8444-444444444444', amount: null },
    ]);
  } finally {
    await client.query(`SET search_path TO ${schema}`);
    await client.query(`DROP SCHEMA ${holds} CASCADE`);
  }
});
